// pack puts the test fonts names in a folder, each with its gzip, as fontpack
// leaves them, and returns the folder.
func pack(t *testing.T, names ...string) string {
	t.Helper()
	dir := t.TempDir()
	for _, n := range names {
		data, err := os.ReadFile(filepath.Join("..", "..", "internal", "ui", "text", "testdata", "fonts", n))
		if err != nil {
			t.Skipf("%s is missing; run make fixtures", n)
		}
		var gz bytes.Buffer
		w := gzip.NewWriter(&gz)
		w.Write(data)
		w.Close()
		if os.WriteFile(filepath.Join(dir, n), data, 0o644) != nil || os.WriteFile(filepath.Join(dir, n+".gz"), gz.Bytes(), 0o644) != nil {
			t.Fatal("couldn't write the fonts")
		}
	}
	return dir
}

var testFonts = []font{
	{"jp.ttf", "jp", text.Regular, text.Japanese},
	{"arabic.ttf", "arabic", text.Regular, text.NoHan},
	{"arabic-semibold.ttf", "arabic", text.SemiBold, text.NoHan},
}

func TestCatalog(t *testing.T) {
	dir := pack(t, "jp.ttf", "arabic.ttf", "arabic-semibold.ttf")
	src, err := catalog(dir, "fonts-9", testFonts)
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	if !strings.HasPrefix(s, "// Code generated by scripts/fontcatalog; DO NOT EDIT.") || !strings.Contains(s, `FontsRelease = "fonts-9"`) {
		t.Fatalf("catalog.go starts\n%s", s[:min(len(s), 300)])
	}
	data, _ := os.ReadFile(filepath.Join(dir, "jp.ttf"))
	gz, _ := os.ReadFile(filepath.Join(dir, "jp.ttf.gz"))
	d, _ := text.NewDownload("jp.ttf", "jp", text.Regular, text.Japanese, data)
	sum := sha256.Sum256(gz)
	want := `{Name: "jp.ttf", Group: "jp", Weight: Regular, Han: Japanese, Size: ` + strconv.Itoa(len(gz)) +
		`, Sum: "` + hex.EncodeToString(sum[:]) + `",` + "\n\t\tCovers: " + strconv.Quote(d.Covers) + "},"
	if !strings.Contains(s, want) {
		t.Fatalf("no entry for jp.ttf like\n%s\nin\n%s", want, s)
	}
	if !strings.Contains(s, `Name: "arabic-semibold.ttf", Group: "arabic", Weight: SemiBold, Han: NoHan`) {
		t.Fatal("no entry for the semibold Arabic")
	}
}

// A font file the catalog doesn't list, a missing gzip and one that unpacks
// to another font each stop it.
func TestCatalogRefuses(t *testing.T) {
	dir := pack(t, "jp.ttf", "arabic.ttf", "arabic-semibold.ttf", "kr.ttf")
	if _, err := catalog(dir, "fonts-9", testFonts); err == nil || !strings.Contains(err.Error(), "kr.ttf") {
		t.Fatalf("an unlisted font: %v", err)
	}
	os.Remove(filepath.Join(dir, "kr.ttf"))
	other, _ := os.ReadFile(filepath.Join(dir, "arabic.ttf.gz"))
	os.WriteFile(filepath.Join(dir, "jp.ttf.gz"), other, 0o644)
	if _, err := catalog(dir, "fonts-9", testFonts); err == nil || !strings.Contains(err.Error(), "jp.ttf.gz") {
		t.Fatalf("a gzip of another font: %v", err)
	}
	os.Remove(filepath.Join(dir, "jp.ttf.gz"))
	if _, err := catalog(dir, "fonts-9", testFonts); err == nil {
		t.Fatal("a missing gzip")
	}
}

// The catalog's own list names every font fontpack makes, once.
func TestFontsListed(t *testing.T) {
	seen := map[string]bool{}
	for _, f := range fonts {
		if seen[f.name] {
			t.Fatalf("%s twice", f.name)
		}
		seen[f.name] = true
	}
	if len(fonts) != 4+2*11+1 {
		t.Fatalf("%d fonts", len(fonts))
	}
}
