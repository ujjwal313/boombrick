// Command fontcatalog writes internal/ui/text/catalog.go for the fonts
// scripts/fontpack.sh made in a folder: each font file there with the gzip of
// it Boombrick downloads.
//
//	go run ./scripts/fontcatalog -tag fonts-1 dist/fonts > internal/ui/text/catalog.go
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/ujjwal313/boombrick/internal/ui/text"
)

// A font is one of the files fontpack makes.
type font struct {
	name, group string
	weight      text.Weight
	han         text.Han
}

// fonts are the downloadable fonts, in the order the engine tries them.
var fonts = []font{
	{"NotoSansSC-Regular.ttf", "sc", text.Regular, text.Simplified},
	{"NotoSansJP-Regular.ttf", "jp", text.Regular, text.Japanese},
	{"NotoSansTC-Regular.ttf", "tc", text.Regular, text.Traditional},
	{"NotoSansKR-Regular.ttf", "kr", text.Regular, text.NoHan},
}

func init() {
	for _, s := range []string{"Arabic", "Hebrew", "Thai", "Devanagari", "Bengali", "Gurmukhi", "Gujarati", "Tamil",
		"Telugu", "Kannada", "Malayalam"} {
		group := strings.ToLower(s)
		fonts = append(fonts, font{"NotoSans" + s + "-Regular.ttf", group, text.Regular, text.NoHan},
			font{"NotoSans" + s + "-SemiBold.ttf", group, text.SemiBold, text.NoHan})
	}
	fonts = append(fonts, font{"NotoEmoji-Regular.ttf", "emoji", text.Regular, text.NoHan})
}

var (
	weightNames = map[text.Weight]string{text.Regular: "Regular", text.SemiBold: "SemiBold"}
	hanNames    = map[text.Han]string{text.NoHan: "NoHan", text.Simplified: "Simplified", text.Japanese: "Japanese",
		text.Traditional: "Traditional"}
)

func main() {
	tag := flag.String("tag", "", "the GitHub release the fonts are published as")
	flag.Parse()
	if flag.NArg() != 1 || *tag == "" {
		fmt.Fprintln(os.Stderr, "usage: fontcatalog -tag fonts-N dir")
		os.Exit(2)
	}
	src, err := catalog(flag.Arg(0), *tag, fonts)
	if err != nil {
		fmt.Fprintln(os.Stderr, "fontcatalog:", err)
		os.Exit(1)
	}
	os.Stdout.Write(src)
}

// catalog is the Go source of the catalog of list, whose files are in dir.
// Every font file in dir must be on the list, and every gzip must unpack to
// its font.
func catalog(dir, tag string, list []font) ([]byte, error) {
	listed := map[string]bool{}
	for _, f := range list {
		listed[f.name] = true
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.ttf"))
	if err != nil {
		return nil, err
	}
	for _, f := range files {
		if !listed[filepath.Base(f)] {
			return nil, fmt.Errorf("%s isn't in the catalog", filepath.Base(f))
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by scripts/fontcatalog; DO NOT EDIT.\n\npackage text\n\n")
	fmt.Fprintf(&b, "// FontsRelease is the GitHub release the downloaded fonts are fetched from.\nconst FontsRelease = %q\n\n", tag)
	fmt.Fprintf(&b, "// Catalog lists the fonts Boombrick downloads the first time text needs them.\n// scripts/fontpack.sh writes it with the fonts.\nvar Catalog = []Download{\n")
	for _, f := range list {
		data, err := os.ReadFile(filepath.Join(dir, f.name))
		if err != nil {
			return nil, err
		}
		gz, err := os.ReadFile(filepath.Join(dir, f.name+".gz"))
		if err != nil {
			return nil, err
		}
		if err := sameAs(gz, data); err != nil {
			return nil, fmt.Errorf("%s.gz: %w", f.name, err)
		}
		d, err := text.NewDownload(f.name, f.group, f.weight, f.han, data)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f.name, err)
		}
		sum := sha256.Sum256(gz)
		fmt.Fprintf(&b, "\t{Name: %q, Group: %q, Weight: %s, Han: %s, Size: %d, Sum: %q,\n\t\tCovers: %q},\n",
			d.Name, d.Group, weightNames[d.Weight], hanNames[d.Han], len(gz), hex.EncodeToString(sum[:]), d.Covers)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// sameAs checks that gz unpacks to data.
func sameAs(gz, data []byte) error {
	r, err := gzip.NewReader(bytes.NewReader(gz))
	if err != nil {
		return err
	}
	got, err := io.ReadAll(r)
	if err != nil {
		return err
	}
	if !bytes.Equal(got, data) {
		return fmt.Errorf("unpacks to something else")
	}
	return nil
}
